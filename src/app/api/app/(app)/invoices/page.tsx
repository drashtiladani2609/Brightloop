import Link from "next/link"
import { ChevronRight, Download, FileText } from "lucide-react"
import { requireRole } from "@/lib/auth"
import { prisma } from "@/lib/prisma"
import { PageHeader } from "@/components/ui/page-header"
import { Card } from "@/components/ui/card"
import { Button } from "@/components/ui/button"
import { StatusBadge } from "@/components/ui/badge"
import { TableWrap, Td, Th, Tr } from "@/components/ui/table"
import { EmptyState } from "@/components/ui/empty-state"
import { SearchBox, FilterSelect, ClearFilters } from "@/components/ui/toolbar"
import { SortHeader } from "@/components/ui/sort-header"
import { Pagination } from "@/components/ui/pagination"
import { FilterTabs } from "@/components/ui/filter-tabs"
import { PAGE_SIZE } from "@/lib/constants"
import { formatDate, money } from "@/lib/utils"
import { paymentState } from "@/server/services/invoices"
import { stateWhere } from "@/lib/invoice-filters"

export const dynamic = "force-dynamic"

const SORTABLE: Record<string, string> = {
  number: "number",
  issueDate: "issueDate",
  dueDate: "dueDate",
  total: "total",
  status: "status"
}

export default async function InvoicesPage({
  searchParams
}: {
  searchParams: { q?: string; status?: string; planId?: string; customerId?: string; page?: string; sort?: string; dir?: string }
}) {
  await requireRole(["ADMIN", "STAFF"])

  const now = new Date()
  const page = Math.max(1, Number(searchParams.page ?? 1))
  const sort = SORTABLE[searchParams.sort ?? "issueDate"] ?? "issueDate"
  const dir = searchParams.dir === "asc" ? "asc" : "desc"
  const q = searchParams.q?.trim()

  const where = {
    ...stateWhere(searchParams.status ?? "", now),
    ...(searchParams.planId ? { subscription: { planId: searchParams.planId } } : {}),
    ...(searchParams.customerId ? { customerId: searchParams.customerId } : {}),
    ...(q ? { OR: [{ number: { contains: q } }, { customer: { name: { contains: q } } }] } : {})
  }

  const [total, rows, paidCount, partialCount, outstandingCount, overdueCount, plans, customers] = await Promise.all([
    prisma.invoice.count({ where }),
    prisma.invoice.findMany({
      where,
      orderBy: { [sort]: dir },
      skip: (page - 1) * PAGE_SIZE,
      take: PAGE_SIZE,
      include: {
        customer: { select: { id: true, name: true } },
        subscription: { select: { number: true } }
      }
    }),
    prisma.invoice.count({ where: { status: "PAID" } }),
    prisma.invoice.count({ where: stateWhere("PARTIAL", now) }),
    prisma.invoice.count({ where: stateWhere("OUTSTANDING", now) }),
    prisma.invoice.count({ where: stateWhere("OVERDUE", now) }),
    prisma.plan.findMany({ select: { id: true, name: true }, orderBy: { name: "asc" } }),
    prisma.customer.findMany({ select: { id: true, name: true }, orderBy: { name: "asc" }, take: 300 })
  ])

  const exportQuery = new URLSearchParams({
    type: "invoices",
    ...(searchParams.status ? { status: searchParams.status } : {}),
    ...(searchParams.customerId ? { customerId: searchParams.customerId } : {}),
    ...(searchParams.planId ? { planId: searchParams.planId } : {}),
    ...(q ? { q } : {})
  })

  return (
    <div className="mx-auto max-w-7xl">
      <PageHeader
        title="Invoices"
        description="Generated by the billing engine. Confirm, send, chase and take payment from here"
        actions={
          <Link href={`/api/export?${exportQuery.toString()}`}>
            <Button size="sm" variant="outline">
              <Download className="h-3.5 w-3.5" /> Export CSV
            </Button>
          </Link>
        }
      />

      <Card>
        <div className="space-y-2 border-b border-border/50 p-3">
          <FilterTabs
            tabs={[
              { value: "", label: "All" },
              { value: "PAID", label: "Paid", count: paidCount },
              { value: "PARTIAL", label: "Partially paid", count: partialCount },
              { value: "OUTSTANDING", label: "Outstanding", count: outstandingCount },
              { value: "OVERDUE", label: "Overdue", count: overdueCount }
            ]}
          />
          <div className="flex flex-col gap-2 sm:flex-row sm:items-center">
            <SearchBox placeholder="Search invoice or customer" />
            <FilterSelect param="planId" placeholder="All plans" options={plans.map((p) => ({ value: p.id, label: p.name }))} />
            <FilterSelect
              param="customerId"
              placeholder="All customers"
              options={customers.map((c) => ({ value: c.id, label: c.name }))}
            />
            <Link href="/invoices?status=OVERDUE" className="sm:ml-auto">
              <Button size="sm" variant="outline" className="border-[color-mix(in_srgb,var(--neg)_40%,transparent)] text-[color:var(--neg)] hover:bg-[color-mix(in_srgb,var(--neg)_10%,transparent)]">
                Chase overdue
              </Button>
            </Link>
            <ClearFilters />
          </div>
        </div>

        {rows.length === 0 ? (
          <EmptyState
            title="No invoices match"
            description={q || searchParams.status ? "Try clearing the filters" : "Run billing to generate the first invoice"}
            icon={<FileText className="h-4 w-4 text-[color:var(--cobalt)]" />}
          />
        ) : (
          <>
            <TableWrap>
              <thead>
                <tr>
                  <Th>
                    <SortHeader label="Number" field="number" />
                  </Th>
                  <Th>Customer</Th>
                  <Th>
                    <SortHeader label="Issued" field="issueDate" />
                  </Th>
                  <Th>
                    <SortHeader label="Due" field="dueDate" />
                  </Th>
                  <Th>Status</Th>
                  <Th className="text-right">Total</Th>
                  <Th className="text-right">Balance</Th>
                  <Th />
                </tr>
              </thead>
              <tbody>
                {rows.map((invoice) => (
                  <Tr key={invoice.id}>
                    <Td>
                      <Link href={`/invoices/${invoice.id}`} className="text-xs font-semibold text-[color:var(--cobalt)] hover:underline">
                        {invoice.number}
                      </Link>
                      <p className="text-[10px] text-muted-foreground">{invoice.subscription.number}</p>
                    </Td>
                    <Td>
                      <Link href={`/customers/${invoice.customer.id}`} className="text-xs hover:underline">
                        {invoice.customer.name}
                      </Link>
                    </Td>
                    <Td className="text-xs text-muted-foreground">{formatDate(invoice.issueDate)}</Td>
                    <Td className="text-xs text-muted-foreground">{formatDate(invoice.dueDate)}</Td>
                    <Td>
                      <StatusBadge status={paymentState(invoice)} />
                    </Td>
                    <Td className="text-right text-xs font-semibold">{money(invoice.total)}</Td>
                    <Td className="text-right text-xs">
                      {invoice.total - invoice.amountPaid > 0.01 ? money(invoice.total - invoice.amountPaid) : "—"}
                    </Td>
                    <Td className="text-right">
                      <Link href={`/invoices/${invoice.id}`}>
                        <Button size="icon" variant="ghost" className="h-8 w-8">
                          <ChevronRight className="h-4 w-4" />
                        </Button>
                      </Link>
                    </Td>
                  </Tr>
                ))}
              </tbody>
            </TableWrap>
            <Pagination page={page} pageCount={Math.ceil(total / PAGE_SIZE)} total={total} />
          </>
        )}
      </Card>
    </div>
  )
}
